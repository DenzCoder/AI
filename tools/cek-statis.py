#!/usr/bin/env python3
"""Static checks that need no Android SDK. Run from the project root: python3 tools/cek-statis.py

Checks: XML files are well-formed; every R.string / R.drawable / @string / @drawable reference resolves;
brackets balance and `package` matches the directory in every Kotlin file; every internal
`import id.asisten.app.*` resolves to a declared symbol; every class named in AndroidManifest.xml exists;
every Hanako expression has an image. It CANNOT find type errors or API misuse: only a real Gradle build does.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

RAIL = Path(__file__).resolve().parent.parent
APP = RAIL / "app" / "src"
PAKET = "id.asisten.app"
galat = []


def lapor(pesan):
    galat.append(pesan)


# --- XML ---
res = APP / "main" / "res"
xml_files = list(res.rglob("*.xml")) + [APP / "main" / "AndroidManifest.xml"]
for f in xml_files:
    try:
        ET.parse(f)
    except ET.ParseError as e:
        lapor(f"XML rusak: {f.relative_to(RAIL)}: {e}")

strings = set()
for f in (res / "values").glob("*.xml"):
    for el in ET.parse(f).getroot().iter("string"):
        strings.add(el.get("name"))
drawables = {p.stem for d in res.glob("drawable*") for p in d.iterdir() if p.is_file()}
drawables |= {p.stem for d in res.glob("mipmap*") for p in d.iterdir() if p.is_file()}
raws = {p.stem for d in res.glob("raw*") for p in d.iterdir() if p.is_file()}

# --- Kotlin ---
kt_files = sorted((APP).rglob("*.kt"))
deklarasi = set()
sumber = {}
for f in kt_files:
    teks = f.read_text(encoding="utf-8")
    sumber[f] = teks
    m = re.search(r"^package\s+([\w.]+)", teks, re.M)
    if not m:
        lapor(f"Tanpa package: {f.relative_to(RAIL)}")
        continue
    paket = m.group(1)
    folder = ".".join(f.relative_to(APP).parts[2:-1])  # drop main|test|androidTest and 'kotlin'
    if paket != folder:
        lapor(f"package {paket} tidak sama dengan folder {folder}: {f.relative_to(RAIL)}")
    for d in re.finditer(
        r"^(?:\s*)(?:(?:public|private|internal|data|enum|sealed|abstract|open|inline|const|suspend|operator|annotation)\s+)*"
        r"(?:class|object|interface|fun|val|var|typealias)\s+(?:<[^\n]*?>\s+)?(?:[\w.<>?]+\.)?(\w+)",
        teks,
        re.M,
    ):
        deklarasi.add(f"{paket}.{d.group(1)}")


def tanpa_komentar_dan_string(teks):
    """Removes comments and the CONTENT of strings with a small state machine (a regex cannot tell a
    `//` inside a string from a comment, nor an apostrophe in a comment from a character literal)."""
    hasil = []
    i, n = 0, len(teks)
    while i < n:
        c = teks[i]
        dua = teks[i:i + 2]
        if dua == "//":
            while i < n and teks[i] != "\n":
                i += 1
        elif dua == "/*":
            kedalaman = 1
            i += 2
            while i < n and kedalaman:
                if teks[i:i + 2] == "/*":
                    kedalaman += 1
                    i += 2
                elif teks[i:i + 2] == "*/":
                    kedalaman -= 1
                    i += 2
                else:
                    i += 1
        elif teks[i:i + 3] == '"""':
            i += 3
            while i < n and teks[i:i + 3] != '"""':
                i += 1
            i += 3
            hasil.append('""')
        elif c == '"':
            i += 1
            while i < n and teks[i] != '"':
                i += 2 if teks[i] == "\\" else 1
            i += 1
            hasil.append('""')
        elif c == "'":
            i += 1
            while i < n and teks[i] != "'":
                i += 2 if teks[i] == "\\" else 1
            i += 1
            hasil.append("''")
        else:
            hasil.append(c)
            i += 1
    return "".join(hasil)


for f, teks in sumber.items():
    bersih = tanpa_komentar_dan_string(teks)
    for buka, tutup in ("()", "[]", "{}"):
        if bersih.count(buka) != bersih.count(tutup):
            lapor(f"Tanda kurung {buka}{tutup} tidak seimbang: {f.relative_to(RAIL)}")
    for m in re.finditer(r"^import\s+(id\.asisten\.app\.[\w.]+)", teks, re.M):
        nama = m.group(1)
        if nama == f"{PAKET}.R" or nama.startswith(f"{PAKET}.R."):
            continue  # generated by the build
        # `import pkg.Objek.anggota` (a member of an object, companion or nested class) is fine when `pkg.Objek` exists.
        sebagai_anggota = nama.rpartition(".")[0] in deklarasi
        if nama not in deklarasi and not sebagai_anggota:
            lapor(f"Import tidak terselesaikan: {nama} di {f.relative_to(RAIL)}")
    for m in re.finditer(r"\bR\.string\.(\w+)", teks):
        if m.group(1) not in strings:
            lapor(f"R.string.{m.group(1)} tidak ada ({f.relative_to(RAIL)})")
    for m in re.finditer(r"\bR\.drawable\.(\w+)", teks):
        if m.group(1) not in drawables:
            lapor(f"R.drawable.{m.group(1)} tidak ada ({f.relative_to(RAIL)})")
    for m in re.finditer(r"\bR\.raw\.(\w+)", teks):
        if m.group(1) not in raws:
            lapor(f"R.raw.{m.group(1)} tidak ada ({f.relative_to(RAIL)})")

for f in xml_files:
    teks = f.read_text(encoding="utf-8")
    for m in re.finditer(r"@string/(\w+)", teks):
        if m.group(1) not in strings:
            lapor(f"@string/{m.group(1)} tidak ada ({f.relative_to(RAIL)})")
    for m in re.finditer(r"@(?:drawable|mipmap)/(\w+)", teks):
        if m.group(1) not in drawables:
            lapor(f"@drawable/{m.group(1)} tidak ada ({f.relative_to(RAIL)})")

# --- Manifest classes ---
manifest = (APP / "main" / "AndroidManifest.xml").read_text(encoding="utf-8")
for m in re.finditer(r'android:name="(\.[\w.]+)"', manifest):
    nama = PAKET + m.group(1)
    if nama not in deklarasi:
        lapor(f"Kelas di manifest tidak ditemukan: {nama}")

# --- Hanako expressions ---
enum_src = (APP / "main/kotlin/id/asisten/app/domain/hanako/EkspresiHanako.kt").read_text(encoding="utf-8")
ui_src = (APP / "main/kotlin/id/asisten/app/ui/hanako/HanakoAvatar.kt").read_text(encoding="utf-8")
for n in re.findall(r'^\s{4}([A-Z]+)\("', enum_src, re.M):
    if f"hanako_{n.lower()}" not in drawables:
        lapor(f"Gambar hanako_{n.lower()} tidak ada")
    if f"EkspresiHanako.{n} -> R.drawable.hanako_{n.lower()}" not in ui_src:
        lapor(f"Ekspresi {n} belum dipetakan ke gambar di HanakoAvatar.kt")

print(f"{len(kt_files)} berkas Kotlin, {len(xml_files)} berkas XML diperiksa")
if galat:
    print("GALAT:")
    for g in galat:
        print(" -", g)
    sys.exit(1)
print("OK: tidak ada masalah statis")
